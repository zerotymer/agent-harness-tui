// Instruction directories and agent guidance blocks (Stage 1 spec §2, §5;
// instruction 0006).
//
// English and Korean guidance are rendered from the same `HarnessConfig`
// so their policy stays equivalent. Only the managed block is written;
// the rest of each guidance file belongs to the user. Skill bodies are never
// inlined, only their location.

import { createOnly, type Desired } from "./apply.js";
import * as backlog from "./backlog.js";
import * as blocks from "./blocks.js";
import { type AgentEntry, agentTitle, builtinAgents, knownAgents } from "./catalog.js";
import { configLayout, type HarnessConfig } from "./contract.js";
import { completedDir, completedLog, type ProjectRoot, RelPath, skillsDir } from "./paths.js";

export const BLOCK_ID = "agent-harness";

export type Lang = "en" | "ko";

/** Guidance files for an agent: English first, then Korean (`<name>_ko.md`). */
export function guidanceFiles(agent: AgentEntry): [Lang, RelPath][] {
  const base = agent.guidance.slice(0, -".md".length);
  return [
    ["en", RelPath.unchecked(agent.guidance)],
    ["ko", RelPath.unchecked(`${base}_ko.md`)],
  ];
}

/** Known configured agents grouped by guidance file (ignoring case), in config order. */
export function groupByGuidance(config: HarnessConfig, agents: AgentEntry[]): AgentEntry[][] {
  const groups: AgentEntry[][] = [];
  for (const [, e] of knownAgents(config.agents, agents)) {
    const g = groups.find((x) => x[0]?.guidance.toLowerCase() === e.guidance.toLowerCase());
    if (g) g.push(e);
    else groups.push([e]);
  }
  return groups;
}

/**
 * Directories and files to plan: instruction dirs, a create-only empty
 * log, the backlog when enabled, and one managed block per guidance file.
 * Agents that share a guidance file share one block.
 */
export async function planItems(
  root: ProjectRoot,
  config: HarnessConfig,
  agents: AgentEntry[] = builtinAgents(),
): Promise<[RelPath[], Desired[]]> {
  const layout = configLayout(config);
  const dirs = [layout.instructions, completedDir(layout)];
  // Never truncates an existing log and records no init event.
  const desired = [createOnly(completedLog(layout), ""), ...(await backlog.planItems(config))];
  for (const group of groupByGuidance(config, agents)) {
    const [first] = group;
    if (!first) continue;
    for (const [lang, file] of guidanceFiles(first)) {
      desired.push(blocks.desired(root, file, "markdown", BLOCK_ID, render(config, group, lang)));
    }
  }
  return [dirs, desired];
}

/**
 * Block body for the agents sharing one guidance file. Agent-specific text
 * goes at the bottom under each agent's title. Every code span appears in
 * both languages.
 */
export function render(config: HarnessConfig, group: AgentEntry[], lang: Lang): string {
  const refs = config.paths.references;
  const out = config.paths.output;
  const layout = configLayout(config);
  const inst = layout.instructions;
  const done = completedDir(layout);
  const log = completedLog(layout);
  const skills = skillsDir();
  const db = config.backlog.path;

  const lines: string[] = [];
  const push = (en: string, ko: string = en) => lines.push(lang === "en" ? en : ko);

  push("## Agent harness", "## 에이전트 하네스");
  push("");
  push(
    "Generated by agent-harness-tui from `harness.toml`. Edit text outside this block; changes inside it are reported as conflicts.",
    "agent-harness-tui가 `harness.toml`에서 생성한 블록이다. 이 블록 밖의 내용은 자유롭게 편집한다. 블록 안을 수정하면 충돌로 보고된다.",
  );
  push("");

  push("### Paths", "### 경로");
  push("");
  push(`- \`${inst}/\`: active work instructions.`, `- \`${inst}/\`: 진행 중인 작업 지시서.`);
  push(
    `- \`${done}/<UUID>.md\`: completed instructions.`,
    `- \`${done}/<UUID>.md\`: 완료된 지시서.`,
  );
  push(`- \`${log}\`: completion log, append-only.`, `- \`${log}\`: 완료 로그, 추가만 가능.`);
  push(`- \`${refs}/\`: reference documents.`, `- \`${refs}/\`: 참조 문서.`);
  push(
    `- \`${skills}/<id>/\`: canonical skill packages. Read \`SKILL.md\` there when its topic comes up; listing a path here does not make an agent discover it automatically.`,
    `- \`${skills}/<id>/\`: 스킬 원본 패키지. 관련 주제가 나오면 해당 위치의 \`SKILL.md\`를 읽는다. 여기에 경로를 적는다고 에이전트가 자동으로 찾는 것은 아니다.`,
  );
  push(
    `- \`${out}/\`: temporary output, local only and not shared. One-way: never read it back as input. Not tracked by Git.`,
    `- \`${out}/\`: 임시 산출물. 로컬 전용이며 공유하지 않는다. 단방향이며 다시 입력으로 읽지 않는다. Git으로 추적하지 않는다.`,
  );
  if (config.backlog.enabled) {
    const sh = inst.join(backlog.SH_FILE);
    const ps1 = inst.join(backlog.PS1_FILE);
    push(
      `- \`${db}\`: backlog (\`backlog\` table) and instruction status (\`instructions\` table), not tracked by Git. Manage it with \`bash ${sh} <command>\` or \`pwsh -File ${ps1} <command>\` (run without arguments for the command list; needs the \`sqlite3\` CLI). \`${log}\` stays the source of truth for completed instructions: the scripts only append to it and sync the database from it. Set \`AGENT_DB_ACTOR\` to record who made a change. Do not change the schema.`,
      `- \`${db}\`: 백로그(\`backlog\` 테이블)와 지시서 상태(\`instructions\` 테이블). Git으로 추적하지 않는다. \`bash ${sh} <command>\` 또는 \`pwsh -File ${ps1} <command>\`로 관리한다(인자 없이 실행하면 명령 목록이 나오며 \`sqlite3\` CLI가 필요하다). 완료된 지시서의 기준은 \`${log}\`이다. 스크립트는 이 로그에 한 줄을 추가하기만 하고, 데이터베이스는 로그를 따라 맞춘다. 변경자를 기록하려면 \`AGENT_DB_ACTOR\`를 설정한다. 스키마는 바꾸지 않는다.`,
    );
  } else {
    push(`- \`${db}\`: optional backlog, disabled.`, `- \`${db}\`: 선택적 백로그, 사용 안 함.`);
  }
  push("");

  push("### Instructions", "### 지시서");
  push("");
  push(
    `- One instruction per file: \`${inst}/NNNN_short-name.md\`, where \`NNNN\` is a 4-digit sequence starting at \`0001\`.`,
    `- 지시서 하나당 파일 하나: \`${inst}/NNNN_short-name.md\`. \`NNNN\`은 \`0001\`부터 시작하는 4자리 순번이다.`,
  );
  push(
    "- Instructions are Markdown written in Korean only and are never translated. English/Korean pairs apply only to references, skills and guidance documents.",
    "- 지시서는 한국어로만 작성하는 Markdown이며 번역하지 않는다. 영어·한국어 쌍은 참조 문서·스킬·지침 문서에만 적용한다.",
  );
  push(
    "- The header holds a fixed UUID and a status (`TODO`, `IN_PROGRESS`, `DONE`):",
    "- 머리말에는 고정된 UUID와 상태(`TODO`, `IN_PROGRESS`, `DONE`)를 적는다:",
  );
  push("");
  push("  ```markdown");
  push("  # 0001 — <title>");
  push("");
  push("  > UUID: <uuid>");
  push("  > Status: TODO");
  push("  ```");
  push("");
  push(
    "- UUIDs must be unique across independent working copies. `NNNN` and the log's line order are local order only, not a global number or timeline across branches.",
    "- UUID는 독립된 작업 사본 사이에서도 고유해야 한다. `NNNN`과 로그의 줄 순서는 로컬 순서일 뿐이며, 브랜치 전체의 고유 번호나 전역 시간순이 아니다.",
  );
  push(
    `- An instruction is complete only when the user explicitly says so; an agent's reply or the end of a session never counts. On completion set \`DONE\`, move the file to \`${done}/<UUID>.md\`, and append one line to \`${log}\`.`,
    `- 지시서는 사용자가 명시적으로 완료라고 할 때만 완료다. 에이전트의 응답이나 세션 종료는 완료가 아니다. 완료 시 상태를 \`DONE\`으로 바꾸고 파일을 \`${done}/<UUID>.md\`로 옮긴 뒤 \`${log}\`에 한 줄을 추가한다.`,
  );
  push(
    "- Log line format: `UUID | summary | datetime with offset`, e.g. `2026-11-16 14:00:00 +0900`.",
    "- 로그 형식: `UUID | summary | datetime with offset`. 예: `2026-11-16 14:00:00 +0900`.",
  );
  push(
    "- Never truncate, rewrite, reorder or renumber the log. On a merge conflict, show it to the user instead of silently dropping history.",
    "- 로그를 비우거나, 고쳐 쓰거나, 순서·번호를 바꾸지 않는다. 병합 충돌이 나면 이력을 몰래 버리지 말고 사용자에게 드러낸다.",
  );
  push("");

  push("### Git");
  push("");
  push(
    `- Track \`${inst}/\` (with \`${done}/\` and \`${log}\`), \`${refs}/\`, \`${skills}/\`, \`harness.toml\`, \`harness.lock.json\` and the root guidance files.`,
    `- 추적: \`${inst}/\`(\`${done}/\`와 \`${log}\` 포함), \`${refs}/\`, \`${skills}/\`, \`harness.toml\`, \`harness.lock.json\`, 루트 지침 파일.`,
  );
  push(
    `- Ignore \`${out}/\`, \`.harness/\` and \`${db}\`, \`${db}-wal\`, \`${db}-shm\`, \`${db}-journal\`. Never put credentials in tracked files.`,
    `- 제외: \`${out}/\`, \`.harness/\`, \`${db}\`, \`${db}-wal\`, \`${db}-shm\`, \`${db}-journal\`. 인증 정보는 추적 파일에 넣지 않는다.`,
  );
  push("");

  push("### Skills", "### 스킬");
  push("");
  if (config.skills.length === 0) {
    push("- None selected yet.", "- 아직 선택한 스킬이 없다.");
  } else {
    push("| ID | Location |", "| ID | 위치 |");
    push("| --- | --- |");
    for (const s of config.skills) push(`| ${s.id} | \`${skills}/${s.id}/\` |`);
  }
  push("");

  for (const agent of group) {
    const name = agentTitle(agent);
    const copies = agent.skillsDir;
    push(`### ${name}`);
    push("");
    if (config.agents.find((a) => a.id === agent.id)?.placement === "copy") {
      push(
        `- Each skill is copied from \`${skills}/<id>/\` to \`${copies}/<id>/\`, where ${name} discovers it. Edit \`${skills}/\`, not the copies: copies are regenerated and not tracked by Git.`,
        `- 각 스킬은 \`${skills}/<id>/\`에서 \`${copies}/<id>/\`로 복사되며, ${name}는 그 위치에서 스킬을 찾는다. 복사본이 아니라 \`${skills}/\`를 편집한다. 복사본은 다시 생성되며 Git으로 추적하지 않는다.`,
      );
    } else {
      push(
        `- Skills are referenced, not copied. ${name} does not discover \`${skills}/\` automatically; read \`${skills}/<id>/SKILL.md\` when its topic comes up.`,
        `- 스킬을 복사하지 않고 참조한다. ${name}는 \`${skills}/\`를 자동으로 찾지 않으므로, 관련 주제가 나오면 \`${skills}/<id>/SKILL.md\`를 읽는다.`,
      );
    }
    push("");
  }
  push(
    "This guidance states policy. It does not enforce file system or command permissions by itself.",
    "이 지침은 정책을 표현할 뿐이며, 파일 시스템·명령 실행 권한을 그 자체로 강제하지 않는다.",
  );
  return `${lines.join("\n")}\n`;
}
