//! Instruction directories and agent guidance blocks (Stage 1 spec §2, §5;
//! instruction 0006).
//!
//! English and Korean guidance are rendered from the same `HarnessConfig`
//! so their policy stays equivalent. Only the managed block is written;
//! the rest of each guidance file belongs to the user. Skill bodies are never
//! inlined, only their location.

use crate::apply::Desired;
use crate::blocks::{self, Syntax};
use crate::contract::{AgentId, HarnessConfig, Placement};
use crate::paths::{Layout, ProjectRoot, RelPath};
use crate::placement::{agent_name, skills_dir};
use std::io;

pub const BLOCK_ID: &str = "agent-harness";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    En,
    Ko,
}

/// Guidance files for an agent: English first, then Korean.
pub fn guidance_files(agent: AgentId) -> [(Lang, RelPath); 2] {
    let base = match agent {
        // Plural on purpose: `AGENTS.md`, never `AGENT.md`.
        AgentId::Codex => "AGENTS",
        AgentId::ClaudeCode => "CLAUDE",
    };
    [
        (
            Lang::En,
            RelPath::parse(&format!("{base}.md")).expect("valid"),
        ),
        (
            Lang::Ko,
            RelPath::parse(&format!("{base}_ko.md")).expect("valid"),
        ),
    ]
}

/// Directories and files to plan: instruction dirs, a create-only empty
/// log, and one managed block per guidance file of each selected agent.
pub fn plan_items(
    root: &ProjectRoot,
    config: &HarnessConfig,
) -> io::Result<(Vec<RelPath>, Vec<Desired>)> {
    let layout = config.layout();
    let dirs = vec![layout.instructions.clone(), layout.completed()];
    // Never truncates an existing log and records no init event.
    let mut desired = vec![Desired::create_only(layout.completed_log(), "")];
    desired.extend(crate::backlog::plan_items(config)?);
    let mut seen = Vec::new();
    for agent in config.agents.iter().map(|a| a.id) {
        if seen.contains(&agent) {
            continue;
        }
        seen.push(agent);
        for (lang, path) in guidance_files(agent) {
            let body = render(config, agent, lang);
            desired.push(blocks::desired(
                root,
                path,
                Syntax::Markdown,
                BLOCK_ID,
                &body,
            )?);
        }
    }
    Ok((dirs, desired))
}

/// Block body for one agent. Every code span appears in both languages.
pub fn render(config: &HarnessConfig, agent: AgentId, lang: Lang) -> String {
    let en = lang == Lang::En;
    let pick = |e: String, k: String| if en { e } else { k };
    let refs = &config.paths.references;
    let out = &config.paths.output;
    let layout = config.layout();
    let inst = &layout.instructions;
    let done = layout.completed();
    let log = layout.completed_log();
    let skills = Layout::skills();
    let db = &config.backlog.path;

    let mut lines: Vec<String> = Vec::new();
    let mut push = |e: String, k: String| lines.push(pick(e, k));

    push("## Agent harness".into(), "## 에이전트 하네스".into());
    push(String::new(), String::new());
    push(
        "Generated by agent-harness-tui from `harness.toml`. Edit text outside this block; changes inside it are reported as conflicts.".into(),
        "agent-harness-tui가 `harness.toml`에서 생성한 블록이다. 이 블록 밖의 내용은 자유롭게 편집한다. 블록 안을 수정하면 충돌로 보고된다.".into(),
    );
    push(String::new(), String::new());

    push("### Paths".into(), "### 경로".into());
    push(String::new(), String::new());
    push(
        format!("- `{inst}/`: active work instructions."),
        format!("- `{inst}/`: 진행 중인 작업 지시서."),
    );
    push(
        format!("- `{done}/<UUID>.md`: completed instructions."),
        format!("- `{done}/<UUID>.md`: 완료된 지시서."),
    );
    push(
        format!("- `{log}`: completion log, append-only."),
        format!("- `{log}`: 완료 로그, 추가만 가능."),
    );
    push(
        format!("- `{refs}/`: reference documents."),
        format!("- `{refs}/`: 참조 문서."),
    );
    push(
        format!(
            "- `{skills}/<id>/`: canonical skill packages. Read `SKILL.md` there when its topic comes up; listing a path here does not make an agent discover it automatically."
        ),
        format!(
            "- `{skills}/<id>/`: 스킬 원본 패키지. 관련 주제가 나오면 해당 위치의 `SKILL.md`를 읽는다. 여기에 경로를 적는다고 에이전트가 자동으로 찾는 것은 아니다."
        ),
    );
    push(
        format!(
            "- `{out}/`: generated output. One-way: never read it back as input. Not tracked by Git."
        ),
        format!(
            "- `{out}/`: 생성 산출물. 단방향이며 다시 입력으로 읽지 않는다. Git으로 추적하지 않는다."
        ),
    );
    if config.backlog.enabled {
        let sh = inst.join(crate::backlog::SH_FILE);
        let ps1 = inst.join(crate::backlog::PS1_FILE);
        push(
            format!(
                "- `{db}`: backlog (`backlog` table) and instruction status (`instructions` table), not tracked by Git. Manage it with `bash {sh} <command>` or `pwsh -File {ps1} <command>` (run without arguments for the command list; needs the `sqlite3` CLI). `{log}` stays the source of truth for completed instructions: the scripts only append to it and sync the database from it. Set `AGENT_DB_ACTOR` to record who made a change. Do not change the schema."
            ),
            format!(
                "- `{db}`: 백로그(`backlog` 테이블)와 지시서 상태(`instructions` 테이블). Git으로 추적하지 않는다. `bash {sh} <command>` 또는 `pwsh -File {ps1} <command>`로 관리한다(인자 없이 실행하면 명령 목록이 나오며 `sqlite3` CLI가 필요하다). 완료된 지시서의 기준은 `{log}`이다. 스크립트는 이 로그에 한 줄을 추가하기만 하고, 데이터베이스는 로그를 따라 맞춘다. 변경자를 기록하려면 `AGENT_DB_ACTOR`를 설정한다. 스키마는 바꾸지 않는다."
            ),
        );
    } else {
        push(
            format!("- `{db}`: optional backlog, disabled."),
            format!("- `{db}`: 선택적 백로그, 사용 안 함."),
        );
    }
    push(String::new(), String::new());

    push("### Instructions".into(), "### 지시서".into());
    push(String::new(), String::new());
    push(
        format!(
            "- One instruction per file: `{inst}/NNNN_short-name.md`, where `NNNN` is a 4-digit sequence starting at `0001`."
        ),
        format!(
            "- 지시서 하나당 파일 하나: `{inst}/NNNN_short-name.md`. `NNNN`은 `0001`부터 시작하는 4자리 순번이다."
        ),
    );
    push(
        "- Instructions are Markdown written in Korean only and are never translated. English/Korean pairs apply only to references, skills and guidance documents.".into(),
        "- 지시서는 한국어로만 작성하는 Markdown이며 번역하지 않는다. 영어·한국어 쌍은 참조 문서·스킬·지침 문서에만 적용한다.".into(),
    );
    push(
        "- The header holds a fixed UUID and a status (`TODO`, `IN_PROGRESS`, `DONE`):".into(),
        "- 머리말에는 고정된 UUID와 상태(`TODO`, `IN_PROGRESS`, `DONE`)를 적는다:".into(),
    );
    push(String::new(), String::new());
    push("  ```markdown".into(), "  ```markdown".into());
    push("  # 0001 — <title>".into(), "  # 0001 — <title>".into());
    push(String::new(), String::new());
    push("  > UUID: <uuid>".into(), "  > UUID: <uuid>".into());
    push("  > Status: TODO".into(), "  > Status: TODO".into());
    push("  ```".into(), "  ```".into());
    push(String::new(), String::new());
    push(
        "- UUIDs must be unique across independent working copies. `NNNN` and the log's line order are local order only, not a global number or timeline across branches.".into(),
        "- UUID는 독립된 작업 사본 사이에서도 고유해야 한다. `NNNN`과 로그의 줄 순서는 로컬 순서일 뿐이며, 브랜치 전체의 고유 번호나 전역 시간순이 아니다.".into(),
    );
    push(
        format!(
            "- An instruction is complete only when the user explicitly says so; an agent's reply or the end of a session never counts. On completion set `DONE`, move the file to `{done}/<UUID>.md`, and append one line to `{log}`."
        ),
        format!(
            "- 지시서는 사용자가 명시적으로 완료라고 할 때만 완료다. 에이전트의 응답이나 세션 종료는 완료가 아니다. 완료 시 상태를 `DONE`으로 바꾸고 파일을 `{done}/<UUID>.md`로 옮긴 뒤 `{log}`에 한 줄을 추가한다."
        ),
    );
    push(
        "- Log line format: `UUID | summary | datetime with offset`, e.g. `2026-11-16 14:00:00 +0900`.".into(),
        "- 로그 형식: `UUID | summary | datetime with offset`. 예: `2026-11-16 14:00:00 +0900`.".into(),
    );
    push(
        "- Never truncate, rewrite, reorder or renumber the log. On a merge conflict, show it to the user instead of silently dropping history.".into(),
        "- 로그를 비우거나, 고쳐 쓰거나, 순서·번호를 바꾸지 않는다. 병합 충돌이 나면 이력을 몰래 버리지 말고 사용자에게 드러낸다.".into(),
    );
    push(String::new(), String::new());

    push("### Git".into(), "### Git".into());
    push(String::new(), String::new());
    push(
        format!(
            "- Track `{inst}/` (with `{done}/` and `{log}`), `{refs}/`, `{skills}/`, `harness.toml`, `harness.lock.json` and the root guidance files."
        ),
        format!(
            "- 추적: `{inst}/`(`{done}/`와 `{log}` 포함), `{refs}/`, `{skills}/`, `harness.toml`, `harness.lock.json`, 루트 지침 파일."
        ),
    );
    push(
        format!(
            "- Ignore `{out}/`, `.harness/` and `{db}`, `{db}-wal`, `{db}-shm`, `{db}-journal`. Never put credentials in tracked files."
        ),
        format!(
            "- 제외: `{out}/`, `.harness/`, `{db}`, `{db}-wal`, `{db}-shm`, `{db}-journal`. 인증 정보는 추적 파일에 넣지 않는다."
        ),
    );
    push(String::new(), String::new());

    push("### Skills".into(), "### 스킬".into());
    push(String::new(), String::new());
    let name = agent_name(agent);
    let copies = skills_dir(agent);
    let placement = config
        .agents
        .iter()
        .find(|a| a.id == agent)
        .map(|a| a.placement);
    if placement == Some(Placement::Copy) {
        push(
            format!(
                "- {name}: each skill is copied from `{skills}/<id>/` to `{copies}/<id>/`, where {name} discovers it. Edit `{skills}/`, not the copies: copies are regenerated and not tracked by Git."
            ),
            format!(
                "- {name}: 각 스킬은 `{skills}/<id>/`에서 `{copies}/<id>/`로 복사되며, {name}는 그 위치에서 스킬을 찾는다. 복사본이 아니라 `{skills}/`를 편집한다. 복사본은 다시 생성되며 Git으로 추적하지 않는다."
            ),
        );
    } else {
        push(
            format!(
                "- {name}: skills are referenced, not copied. {name} does not discover `{skills}/` automatically; read `{skills}/<id>/SKILL.md` when its topic comes up."
            ),
            format!(
                "- {name}: 스킬을 복사하지 않고 참조한다. {name}는 `{skills}/`를 자동으로 찾지 않으므로, 관련 주제가 나오면 `{skills}/<id>/SKILL.md`를 읽는다."
            ),
        );
    }
    if config.skills.is_empty() {
        push(
            "- None selected yet.".into(),
            "- 아직 선택한 스킬이 없다.".into(),
        );
    } else {
        push("| ID | Location |".into(), "| ID | 위치 |".into());
        push("| --- | --- |".into(), "| --- | --- |".into());
        for s in &config.skills {
            let row = format!("| {} | `{skills}/{}/` |", s.id, s.id);
            push(row.clone(), row);
        }
    }
    push(String::new(), String::new());
    push(
        "This guidance states policy. It does not enforce file system or command permissions by itself.".into(),
        "이 지침은 정책을 표현할 뿐이며, 파일 시스템·명령 실행 권한을 그 자체로 강제하지 않는다.".into(),
    );
    lines.join("\n") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::apply::{Action, apply, plan};
    use crate::contract::{
        AgentConfig, ContractFile, HarnessState, Placement, SkillConfig, SourceConfig, SourceKind,
    };
    use std::collections::BTreeSet;
    use std::fs;
    use std::path::PathBuf;
    use std::sync::atomic::{AtomicUsize, Ordering};

    struct TempProject(PathBuf);

    impl TempProject {
        fn new() -> Self {
            static N: AtomicUsize = AtomicUsize::new(0);
            let dir = std::env::temp_dir().join(format!(
                "aht-guidance-{}-{}",
                std::process::id(),
                N.fetch_add(1, Ordering::SeqCst)
            ));
            fs::create_dir_all(&dir).unwrap();
            Self(dir)
        }
        fn root(&self) -> ProjectRoot {
            ProjectRoot::new(&self.0).unwrap()
        }
        fn read(&self, rel: &str) -> String {
            fs::read_to_string(self.0.join(rel)).unwrap()
        }
    }

    impl Drop for TempProject {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

    fn config() -> HarnessConfig {
        let mut c = HarnessConfig::default();
        c.paths.references = RelPath::parse("docs/참조 문서").unwrap();
        c.paths.output = RelPath::parse(".out").unwrap();
        c.agents = vec![
            AgentConfig {
                id: AgentId::ClaudeCode,
                placement: Placement::Reference,
            },
            AgentConfig {
                id: AgentId::Codex,
                placement: Placement::Reference,
            },
        ];
        c.sources = vec![SourceConfig {
            id: "local".into(),
            kind: SourceKind::LocalDir,
            path: Some(RelPath::parse("vendor").unwrap()),
            token_env: None,
        }];
        c.skills = vec![SkillConfig {
            id: "review".into(),
            source: "local".into(),
            reference: "review".into(),
            page_type: None,
        }];
        c.validate().unwrap();
        c
    }

    fn code_spans(text: &str) -> BTreeSet<String> {
        text.split('`')
            .skip(1)
            .step_by(2)
            .map(str::to_string)
            .collect()
    }

    fn run(
        p: &TempProject,
        state: &mut HarnessState,
        c: &HarnessConfig,
    ) -> crate::apply::ApplyReport {
        let root = p.root();
        let (dirs, desired) = plan_items(&root, c).unwrap();
        let pl = plan(&root, state, &dirs, desired).unwrap();
        apply(&root, &pl, state).unwrap()
    }

    #[test]
    fn english_and_korean_share_every_path_and_value() {
        for backlog in [false, true] {
            let mut c = config();
            c.backlog.enabled = backlog;
            let (en, ko) = (
                render(&c, AgentId::ClaudeCode, Lang::En),
                render(&c, AgentId::ClaudeCode, Lang::Ko),
            );
            assert_eq!(code_spans(&en), code_spans(&ko));
            assert_eq!(en.lines().count(), ko.lines().count(), "same structure");
            for must in [
                "docs/참조 문서/",
                ".out/",
                "instructions/.completed/<UUID>.md",
                "instructions/agent.db-wal",
            ] {
                assert!(code_spans(&en).contains(must), "{must}");
            }
            assert!(!en.contains("agent-harness:"), "no marker text in the body");
        }
    }

    #[test]
    fn placement_line_matches_agent_and_language() {
        let mut c = config();
        c.agents[1].placement = Placement::Copy; // codex copies, claude references
        let codex_en = render(&c, AgentId::Codex, Lang::En);
        let codex_ko = render(&c, AgentId::Codex, Lang::Ko);
        assert!(codex_en.contains("`.agents/skills/<id>/`"));
        assert_eq!(code_spans(&codex_en), code_spans(&codex_ko));
        let claude = render(&c, AgentId::ClaudeCode, Lang::En);
        assert!(claude.contains("referenced, not copied"));
        assert!(!claude.contains(".claude/skills"));
    }

    #[test]
    fn skills_are_listed_not_inlined() {
        let en = render(&config(), AgentId::ClaudeCode, Lang::En);
        assert!(en.contains("| review | `.skills/review/` |"));
        let mut c = config();
        c.skills.clear();
        assert!(render(&c, AgentId::ClaudeCode, Lang::Ko).contains("아직 선택한 스킬이 없다"));
    }

    #[test]
    fn agents_get_plural_agents_md_and_claude_md() {
        let names: Vec<String> = [AgentId::Codex, AgentId::ClaudeCode]
            .into_iter()
            .flat_map(guidance_files)
            .map(|(_, p)| p.to_string())
            .collect();
        assert_eq!(
            names,
            ["AGENTS.md", "AGENTS_ko.md", "CLAUDE.md", "CLAUDE_ko.md"]
        );
    }

    #[test]
    fn initializes_project_and_is_idempotent() {
        let p = TempProject::new();
        let mut state = HarnessState::default();
        let report = run(&p, &mut state, &config());
        assert_eq!(report.failed, None);
        assert!(p.0.join("instructions/.completed").is_dir());
        assert_eq!(p.read("instructions/completed.log"), "");
        for f in ["AGENTS.md", "AGENTS_ko.md", "CLAUDE.md", "CLAUDE_ko.md"] {
            assert!(
                p.read(f)
                    .contains("<!-- agent-harness:begin agent-harness -->"),
                "{f}"
            );
        }
        let again = run(&p, &mut state, &config());
        assert_eq!(again.apply_id, None, "repeat run changes nothing");
        assert_eq!(
            p.read("CLAUDE.md").matches("agent-harness:begin").count(),
            1
        );
    }

    #[test]
    fn preserves_existing_guidance_and_log() {
        let p = TempProject::new();
        fs::create_dir_all(p.0.join("instructions")).unwrap();
        fs::write(
            p.0.join("instructions/completed.log"),
            "u1 | old | 2026-01-01 00:00:00 +0900\n",
        )
        .unwrap();
        fs::write(p.0.join("CLAUDE.md"), "# Team rules\n\nBe kind.\n").unwrap();
        let mut state = HarnessState::default();
        let mut c = config();
        c.agents.truncate(1);
        let report = run(&p, &mut state, &c);
        assert_eq!(report.preserved, vec!["instructions/completed.log"]);
        assert_eq!(
            p.read("instructions/completed.log"),
            "u1 | old | 2026-01-01 00:00:00 +0900\n"
        );
        let claude = p.read("CLAUDE.md");
        assert!(claude.starts_with("# Team rules\n\nBe kind.\n\n<!-- agent-harness:begin"));
        assert!(!p.0.join("AGENTS.md").exists(), "only selected agents");
    }

    #[test]
    fn config_change_updates_block_only() {
        let p = TempProject::new();
        let mut state = HarnessState::default();
        run(&p, &mut state, &config());
        let mut c = config();
        c.backlog.enabled = true;
        let root = p.root();
        let (dirs, desired) = plan_items(&root, &c).unwrap();
        let pl = plan(&root, &state, &dirs, desired).unwrap();
        let updated: Vec<_> = pl
            .items
            .iter()
            .filter(|i| i.action == Action::Update)
            .map(|i| i.desired.path.to_string())
            .collect();
        assert_eq!(
            updated,
            ["CLAUDE.md", "CLAUDE_ko.md", "AGENTS.md", "AGENTS_ko.md"]
        );
    }
}
